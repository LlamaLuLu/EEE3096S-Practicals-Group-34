/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  HAL_Init();
  SystemClock_Config();

  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();

  init_LCD();

  /* Start TIM3 base and PWM (TIM3 ARR already set in MX_TIM3_Init to DAC_MAX_12B) */
  if (HAL_TIM_Base_Start(&htim3) != HAL_OK) Error_Handler();
  if (HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3) != HAL_OK) Error_Handler();

  /* Configure TIM2 period to generate CC1 events at the sample rate */
  if (TIM2_Ticks == 0u) TIM2_Ticks = 1u; /* sanity */
  htim2.Init.Period = TIM2_Ticks - 1u;
  if (HAL_TIM_Base_Init(&htim2) != HAL_OK) Error_Handler();

  /* Set compare value to generate CC1 events; place in middle of period */
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, TIM2_Ticks / 2u);

  /* Start TIM2 OC (TIM2 base already init'd) */
  if (HAL_TIM_OC_Start(&htim2, TIM_CHANNEL_1) != HAL_OK) Error_Handler();

  /* Start DMA transferring initial waveform (Sin_LUT) */
  if (HAL_DMA_Start_IT(
      &hdma_tim2_ch1,
      (uint32_t)Sin_LUT,            // source LUT (start with sine)
      DestAddress,                  // destination = TIM3 CCR3
      NS) != HAL_OK) {
    Error_Handler();
  }

  /* Enable DMA requests from TIM2 CC1 */
  __HAL_TIM_ENABLE_DMA(&htim2, TIM_DMA_CC1);

  /* Display initial waveform name on LCD */
  lcd_command(CLEAR);
  HAL_Delay(10);
  lcd_putstring(wave_names[wave_idx]); /* wave_idx == 0 -> "Sine" */

  /* main loop does nothing; waveform generation is DMA/timer driven */
  while (1)
  {
    __WFI(); /* optionally wait for interrupt to save power */
  }
}

