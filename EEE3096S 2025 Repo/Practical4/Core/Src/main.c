/* Helper to (re)start DMA with waveform index (safe) */
static void restart_dma_with_wave(uint32_t idx)
{
    if (idx >= NUM_WAVES) return;

    /* disable TIM2 DMA requests so no new transfers are issued while reconfiguring */
    __HAL_TIM_DISABLE_DMA(&htim2, TIM_DMA_CC1);

    /* abort any running DMA transfer (non-blocking interrupt-aware) */
    (void) HAL_DMA_Abort_IT(&hdma_tim2_ch1);

    /* wait until DMA state is ready (abort completed) */
    while (hdma_tim2_ch1.State != HAL_DMA_STATE_READY) {
        /* small spin; should be quick */
    }

    /* (re)start DMA from the desired LUT */
    if (HAL_DMA_Start_IT(&hdma_tim2_ch1,
                         (uint32_t)waveforms[idx],
                         DestAddress,
                         NS) != HAL_OK) {
        Error_Handler();
    }

    /* re-enable TIM2 -> DMA requests */
    __HAL_TIM_ENABLE_DMA(&htim2, TIM_DMA_CC1);
}

