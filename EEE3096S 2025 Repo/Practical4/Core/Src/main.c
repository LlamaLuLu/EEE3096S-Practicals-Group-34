/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU init */
  HAL_Init();
  SystemClock_Config();

  /* init peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();

  /* Start TIM3 PWM on CH3 (TIM3 configured with ARR = DAC_MAX_12B) */
  if (HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3) != HAL_OK) Error_Handler();

  /* configure and start initial waveform (index 0) */
  set_waveform(0);

  /* initialize LCD if available */
  init_LCD();
  HAL_Delay(20);
  lcd_command(CLEAR);
  lcd_command(CURSOR_HOME);
  lcd_putstring("Wave: ");
  lcd_putstring((char*)wave_names[current_wave]);

  /* main loop: all work is DMA/timer driven; button toggles are in EXTI handler */
  while (1)
  {
      __WFI(); /* low-power wait-for-interrupt */
  }
}

