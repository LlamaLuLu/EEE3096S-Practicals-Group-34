/* Helper: calculate TIM2_Ticks for given sample count and F_SIGNAL
   ticks = round(TIM2CLK / (samples_per_cycle * F_SIGNAL))
   Use 64-bit intermediate to avoid overflow.
*/
static uint32_t calc_tim2_ticks(uint32_t samples_per_cycle)
{
    uint64_t denom = (uint64_t)samples_per_cycle * (uint64_t)F_SIGNAL;
    uint64_t numer = (uint64_t)TIM2CLK;
    return (uint32_t)((numer + denom/2u) / denom);
}

/* set_waveform: safely switch DMA source and TIM2 timing for waveform idx */
void set_waveform(uint32_t idx)
{
    if (idx >= NUM_WAVES) return;

    uint32_t new_len = wave_lens[idx];
    const uint16_t *new_src = waveforms[idx];

    /* compute new TIM2 ticks */
    uint32_t new_ticks = calc_tim2_ticks(new_len);
    if (new_ticks == 0u) new_ticks = 1u; /* sanity */

    /* disable DMA requests from TIM2 while reconfiguring */
    __HAL_TIM_DISABLE_DMA(&htim2, TIM_DMA_CC1);

    /* abort any running DMA transfer */
    (void)HAL_DMA_Abort_IT(&hdma_tim2_ch1);

    /* wait until DMA state is ready (abort completed) */
    while (hdma_tim2_ch1.State != HAL_DMA_STATE_READY) {
        /* small spin — abort should be quick */
    }

    /* reconfigure TIM2 period */
    TIM2_Ticks = new_ticks;
    htim2.Init.Period = TIM2_Ticks - 1u;
    if (HAL_TIM_Base_Init(&htim2) != HAL_OK) {
        Error_Handler();
    }

    /* set compare in the middle of the period so OC event occurs reliably */
    __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, TIM2_Ticks / 2u);

    /* ensure TIM2 OC is running */
    if (HAL_TIM_OC_Start(&htim2, TIM_CHANNEL_1) != HAL_OK) {
        Error_Handler();
    }

    /* start DMA: memory -> peripheral (TIM3->CCR3), length = new_len */
    if (HAL_DMA_Start_IT(&hdma_tim2_ch1,
                         (uint32_t)new_src,
                         DestAddress,
                         new_len) != HAL_OK) {
        Error_Handler();
    }

    /* enable DMA requests from TIM2 CC1 again */
    __HAL_TIM_ENABLE_DMA(&htim2, TIM_DMA_CC1);

    /* update current wave index and LCD */
    current_wave = idx;
    lcd_command(CLEAR);
    lcd_command(CURSOR_HOME);
    lcd_putstring("Wave: ");
    lcd_putstring((char*)wave_names[idx]);
}

